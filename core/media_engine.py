# Design Tokens: ASS Color Palettes (BGR Hex format for libass)
COLOR_MAP_BGR_ASS: Dict[str, str] = {
    "Yellow": "&H0015CCFA&",   # TikTok Gold #FACC15
    "Green": "&H0081B910&",    # Electric Emerald #10B981
    "Cyan": "&H00FFFF00&",     # Cyber Cyan #00FFFF
    "White": "&H00FFFFFF&",    # Crisp White
}

FONT_SIZE_MAP: Dict[str, int] = {
    "Small": 48,
    "Medium": 60,
    "Large": 74,
}

ASPECT_RATIOS: Dict[str, str] = {
    "9:16 (Vertical Short)": "9:16",
    "1:1 (Square Feed)": "1:1",
    "16:9 (Horizontal Original)": "16:9",
}

def extract_youtube_video_id(url: str) -> Optional[str]:
    """Extracts the 11-character YouTube video ID from valid YouTube URLs."""
    if not url:
        return None
    url = url.strip()
    if re.fullmatch(r"^[a-zA-Z0-9_-]{11}$", url):
        return url

    # Restrict strictly to valid YouTube domains
    if not re.search(r"^(?:https?:\/\/)?(?:[a-zA-Z0-9-]+\.)?(?:youtube\.com|youtu\.be)\/", url):
        return None

    patterns = [
        r"(?:v=|\/embed\/|\/shorts\/|\/live\/)([0-9A-Za-z_-]{11})",
        r"youtu\.be\/([0-9A-Za-z_-]{11})",
        r"[?&]v=([0-9A-Za-z_-]{11})",
    ]
    for pattern in patterns:
        match = re.search(pattern, url)
        if match:
            return match.group(1)
    return None

def is_valid_youtube_url(url: str) -> bool:
    """Validates if string is a recognized YouTube URL format."""
    return extract_youtube_video_id(url) is not None

def parse_time_to_seconds(time_str: str) -> Optional[float]:
    """Parses HH:MM:SS, MM:SS, or seconds string into total seconds."""
    if not time_str or not time_str.strip():
        return None
    clean = time_str.strip()
    try:
        if clean.replace(".", "", 1).isdigit():
            val = float(clean)
            return val if val >= 0 else None
    except ValueError:
        pass

    parts = clean.split(":")
    try:
        parts_f = [float(p) for p in parts]
    except ValueError:
        return None

    if any(p < 0 for p in parts_f):
        return None

    if len(parts_f) == 3:
        return parts_f[0] * 3600 + parts_f[1] * 60 + parts_f[2]
    elif len(parts_f) == 2:
        return parts_f[0] * 60 + parts_f[1]
    elif len(parts_f) == 1:
        return parts_f[0]
    return None

def format_seconds_to_hms(seconds: float) -> str:
    """Converts total seconds into standard HH:MM:SS format."""
    sec = max(0, int(seconds))
    hrs = sec // 3600
    rem = sec % 3600
    mins = rem // 60
    secs = rem % 60
    return f"{hrs:02d}:{mins:02d}:{secs:02d}"

def format_ass_time(seconds: float) -> str:
    """Formats seconds into ASS subtitle timestamp format (H:MM:SS.cs)."""
    safe_sec = max(0.0, seconds)
    total_cs = int(round(safe_sec * 100))
    cs = total_cs % 100
    total_secs = total_cs // 100
    hours = total_secs // 3600
    rem = total_secs % 3600
    minutes = rem // 60
    secs = rem % 60
    return f"{hours}:{minutes:02d}:{secs:02d}.{cs:02d}"

def generate_ass_subtitle_file(
    words_data: List[Dict[str, Any]],
    output_ass_path: Path,
    font_size: str = "Medium",
    highlight_color: str = "Yellow",
    words_per_screen: int = 3,
) -> None:
    """Generates an Advanced SubStation Alpha (.ass) subtitle file with word-level karaoke styling."""
    font_pt = FONT_SIZE_MAP.get(font_size, 60)
    highlight_ass = COLOR_MAP_BGR_ASS.get(highlight_color, "&H0015CCFA&")
    default_white_ass = "&H00FFFFFF&"
    margin_v = 240 if font_pt == 60 else (220 if font_pt == 48 else 260)

    ass_lines = [
        "[Script Info]",
        "; Script generated by ChopChop-ai High-Retention Engine",
        "Title: ChopChop Dynamic Subtitles",
        "ScriptType: v4.00+",
        "PlayResX: 1080",
        "PlayResY: 1920",
        "ScaledBorderAndShadow: yes",
        "YCbCr Matrix: TV.709",
        "",
        "[V4+ Styles]",
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
        f"Style: Default,DejaVu Sans,{font_pt},{default_white_ass},{highlight_ass},&H00000000,&H80000000,-1,0,0,0,100,100,1.2,0,1,5.0,2.5,2,40,40,{margin_v},1",
        "",
        "[Events]",
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    ]

    if not words_data:
        output_ass_path.write_text("\n".join(ass_lines), encoding="utf-8")
        return

    # Group words into chunks
    for i in range(0, len(words_data), words_per_screen):
        grp = words_data[i : i + words_per_screen]
        for active_idx, target_word in enumerate(grp):
            start_t = target_word["start"]
            end_t = target_word["end"] if target_word["end"] > start_t else start_t + 0.3
            start_str = format_ass_time(start_t)
            end_str = format_ass_time(end_t)
            rendered = [
                f"{{\\c{highlight_ass}}}{w['word']}{{\\c{default_white_ass}}}"
                if idx == active_idx
                else w["word"]
                for idx, w in enumerate(grp)
            ]
            ass_lines.append(
                f"Dialogue: 0,{start_str},{end_str},Default,,0,0,0,,{' '.join(rendered)}"
            )

    output_ass_path.write_text("\n".join(ass_lines), encoding="utf-8")

def convert_aspect_ratio_and_frame(
    input_video: Path,
    output_video: Path,
    aspect_ratio: str,
) -> bool:
    """Dynamic center crop to 9:16 (1080x1920) or 1:1 using FFmpeg."""
    if aspect_ratio == "9:16":
        vf_filter = "crop=ih*(9/16):ih,scale=1080:1920:flags=lanczos"
    elif aspect_ratio == "1:1":
        vf_filter = "crop=ih:ih,scale=1080:1080:flags=lanczos"
    else:
        vf_filter = "scale=1920:1080:force_original_aspect_ratio=decrease,pad=1920:1080:(ow-iw)/2:(oh-ih)/2"

    cmd = [
        "ffmpeg",
        "-y",
        "-i",
        str(input_video),
        "-vf",
        vf_filter,
        "-c:v",
        "libx264",
        "-preset",
        "medium",
        "-crf",
        "18",
        "-c:a",
        "aac",
        "-b:a",
        "192k",
        "-ar",
        "44100",
        "-movflags",
        "+faststart",
        str(output_video),
    ]
    subprocess.run(
        cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True
    )
    return True

def extract_audio_from_clip(video_path: Path, audio_path: Path) -> bool:
    """Extracts 16kHz mono WAV audio for Whisper speech recognition."""
    cmd = [
        "ffmpeg",
        "-y",
        "-i",
        str(video_path),
        "-vn",
        "-acodec",
        "pcm_s16le",
        "-ar",
        "16000",
        "-ac",
        "1",
        str(audio_path),
    ]
    subprocess.run(
        cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True
    )
    return True

def burn_subtitles_into_video(
    input_video: Path,
    ass_subtitle_file: Path,
    output_video: Path,
) -> bool:
    """Burns ASS subtitles into video stream."""
    escaped_ass_path = str(ass_subtitle_file.resolve()).replace("\\", "/").replace(":", "\\:")
    cmd = [
        "ffmpeg",
        "-y",
        "-i",
        str(input_video),
        "-vf",
        f"ass='{escaped_ass_path}'",
        "-c:v",
        "libx264",
        "-preset",
        "medium",
        "-crf",
        "20",
        "-c:a",
        "copy",
        "-movflags",
        "+faststart",
        str(output_video),
    ]
    subprocess.run(
        cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True
    )
    return True
