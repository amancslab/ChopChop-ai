import { FontSizeChoice, HighlightColorChoice, SubtitleWord } from '../types';

export const ASS_COLOR_MAP: Record<HighlightColorChoice, { ass: string; hex: string; name: string }> = {
  Yellow: { ass: '&H0015CCFA&', hex: '#FACC15', name: 'TikTok Gold' },
  Green: { ass: '&H0081B910&', hex: '#10B981', name: 'Electric Emerald' },
  Red: { ass: '&H006633FF&', hex: '#FF3366', name: 'Cyber Neon Red' },
  Cyan: { ass: '&H00FFFF00&', hex: '#00FFFF', name: 'Cyber Cyan' },
};

export const ASS_FONT_SIZES: Record<FontSizeChoice, { size: number; marginV: number }> = {
  Small: { size: 48, marginV: 220 },
  Medium: { size: 60, marginV: 240 },
  Large: { size: 74, marginV: 260 },
};

export function formatAssTime(seconds: number): string {
  const safeSec = Math.max(0, seconds);
  const totalCs = Math.round(safeSec * 100);
  const cs = totalCs % 100;
  const totalSecs = Math.floor(totalCs / 100);
  const hours = Math.floor(totalSecs / 3600);
  const rem = totalSecs % 3600;
  const minutes = Math.floor(rem / 60);
  const secs = rem % 60;
  return `${hours}:${String(minutes).padStart(2, '0')}:${String(secs).padStart(2, '0')}.${String(cs).padStart(2, '0')}`;
}

export function generateAssContent(
  words: SubtitleWord[],
  fontSizeChoice: FontSizeChoice = 'Medium',
  highlightColorChoice: HighlightColorChoice = 'Yellow',
  wordsPerScreen: number = 3
): string {
  const fontMeta = ASS_FONT_SIZES[fontSizeChoice] || ASS_FONT_SIZES.Medium;
  const colorMeta = ASS_COLOR_MAP[highlightColorChoice] || ASS_COLOR_MAP.Yellow;
  const defaultWhite = '&H00FFFFFF&';

  const lines: string[] = [
    '[Script Info]',
    '; Script generated by ChopChop.ai Razor Subtitle Engine',
    'Title: ChopChop.ai Dynamic High-Retention Subtitles',
    'ScriptType: v4.00+',
    'PlayResX: 1080',
    'PlayResY: 1920',
    'ScaledBorderAndShadow: yes',
    'YCbCr Matrix: TV.709',
    '',
    '[V4+ Styles]',
    'Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding',
    `Style: Default,Arial Black,${fontMeta.size},${defaultWhite},${colorMeta.ass},&H00000000,&H80000000,-1,0,0,0,100,100,1.2,0,1,5.0,2.5,2,40,40,${fontMeta.marginV},1`,
    '',
    '[Events]',
    'Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text',
  ];

  if (!words || words.length === 0) {
    return lines.join('\n');
  }

  // Group words into phrases (3 words per line for high retention)
  for (let i = 0; i < words.length; i += wordsPerScreen) {
    const group = words.slice(i, i + wordsPerScreen);

    group.forEach((targetWord, activeIdx) => {
      const startT = targetWord.start;
      let endT = targetWord.end;

      if (endT <= startT) {
        endT = startT + 0.25;
      }

      if (activeIdx + 1 < group.length) {
        const nextStart = group[activeIdx + 1].start;
        if (nextStart > endT && nextStart - endT < 0.2) {
          endT = nextStart;
        }
      }

      const startStr = formatAssTime(startT);
      const endStr = formatAssTime(endT);

      const formattedWords = group.map((w, idx) => {
        if (idx === activeIdx) {
          return `{\\c${colorMeta.ass}}${w.word.toUpperCase()}{\\c${defaultWhite}}`;
        }
        return w.word.toUpperCase();
      });

      const lineText = formattedWords.join(' ');
      lines.push(`Dialogue: 0,${startStr},${endStr},Default,,0,0,0,,${lineText}`);
    });
  }

  return lines.join('\n');
}
